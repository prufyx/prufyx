package k8sdeclared

import (
	"fmt"
	"strings"
)

var reasonText = map[string]string{
	ReasonNoSource:        "no upstream declaration was found in the reviewed sources",
	ReasonSourceAbsent:    "the reviewed file does not exist at this tag",
	ReasonNoDeclaration:   "the reviewed file declares no Kubernetes version",
	ReasonNotLowerBound:   "the chart constraint is not a single lower bound, so no minimum is read from it",
	ReasonSourceUnusable:  "the reviewed file could not be read in the strict subset",
	ReasonMatrixRowAbsent: "the compatibility table has no row for this release line",
	ReasonMatrixLayout:    "the compatibility table layout is not the reviewed one",
	ReasonMatrixLowerEdge: "the table row starts at its first column, so it states no lower bound",
}

func mdText(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, "|", "\\|"), "\n", " ") }

// Markdown renders the table. Wording: "declared by upstream" only.
func Markdown(o Output) string {
	var b strings.Builder
	b.WriteString("# Kubernetes versions declared by upstream per project release\n\n")
	b.WriteString("<!-- Generated by `prufyx-maintainer k8s-declared`; do not edit. -->\n\n")
	b.WriteString(o.Label + "\n\n")
	b.WriteString("How to read it:\n\n")
	b.WriteString("- A minimum is shown as a minimum, never as a range. A maximum appears only where a compatibility table row states a lower and an upper column with a cross after it. A row whose ticks run to the last column is shown as a minimum, with that column named as the last one the table lists, not as a maximum.\n")
	b.WriteString("- A chart row is what that chart declares in its `kubeVersion`. It is not mapped to the application version.\n")
	b.WriteString("- \"Not declared upstream\" means nothing citable was found at that tag in the reviewed source. It is not a statement that the release works or fails on any Kubernetes version.\n")
	b.WriteString("- Each cited row names the repository, the tag, the commit the tag resolved to through the upstream API, the file path, the cited lines and the file digest. The JSON file next to this one holds the full commit, blob, file and API response digests.\n\n")
	for _, p := range o.Projects {
		fmt.Fprintf(&b, "## %s\n\nRepository: `%s`.\n\n", p.Project, p.Repo)
		b.WriteString("| Release line | Tag | Declared by upstream | Source | Citation |\n|---|---|---|---|---|\n")
		for _, r := range p.Releases {
			if r.Status == StatusNotDeclared {
				txt := "not declared upstream: " + reasonText[r.Reason]
				if r.ConstraintRaw != "" {
					txt += " (`" + mdText(r.ConstraintRaw) + "`)"
				}
				fmt.Fprintf(&b, "| %s | `%s` | %s | | |\n", r.Line, r.Tag, txt)
				continue
			}
			c := r.Citation
			var decl, src string
			switch r.SourceKind {
			case KindChart:
				decl = fmt.Sprintf("minimum %s (the chart declares `%s`); no maximum declared", r.Minimum, mdText(r.ConstraintRaw))
				src = "chart `kubeVersion`, declared by the chart"
			default:
				if r.TableLastColumn != "" {
					decl = fmt.Sprintf("minimum %s; the table lists up to %s (its last column, not an upstream maximum)", r.Minimum, r.TableLastColumn)
				} else {
					decl = fmt.Sprintf("range %s to %s", r.Minimum, r.Maximum)
				}
				src = "upstream compatibility table"
			}
			var lines []string
			for _, l := range c.CitedLines {
				lines = append(lines, fmt.Sprintf("L%d", l.Line))
			}
			cite := fmt.Sprintf("`%s@%s` `%s` %s, file sha256 `%s`", c.Repo, c.Commit, c.Path, strings.Join(lines, ", "), c.FileSHA256[:16])
			fmt.Fprintf(&b, "| %s | `%s` | %s | %s | %s |\n", r.Line, r.Tag, decl, src, cite)
		}
		b.WriteString("\n")
	}
	return b.String()
}
