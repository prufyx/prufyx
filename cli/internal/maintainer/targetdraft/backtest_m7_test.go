func TestM7StopSubjectsAndGeneratedMinFromArePrinted(t *testing.T) {
	f := newBT(t)
	raw := readFileT(t, f.dir+"/expected-beta.json")
	if err := os.WriteFile(f.dir+"/expected-beta.json", bytes.Replace(raw, []byte(`"minFrom": "1.1"`), []byte(`"minFrom": "1.2"`), 1), 0o644); err != nil {
		t.Fatal(err)
	}
	old := generate
	defer func() { generate = old }()
	generate = func(in Input) (*Result, error) {
		if in.Slug == "alpha" {
			return nil, &StopError{Stops: []Stop{{Code: StopReservedGroup, Subject: "apps", Next: "x"}, {Code: StopNoCRDSource, Subject: "a/b.yaml", Next: "x"}}}
		}
		return old(in)
	}
	f.m["seeds"] = []any{map[string]any{"entry": "beta", "kind": "path"}}
	_, so, _ := f.run(t, btOpen)
	if !strings.Contains(so, "alpha typed-stop stops=no-crd-source,reserved-group half=A stopSubjects=no-crd-source:a/b.yaml;reserved-group:apps\n") {
		t.Errorf("alpha line: %s", so)
	}
	if !strings.Contains(so, "beta differs cause=window fields=minFrom half=A generatedMinFrom=1.1\n") {
		t.Errorf("beta line: %s", so)
	}
	if !strings.Contains(so, "HISTOGRAM ") || !strings.Contains(so, "stop:reserved-group=1") {
		t.Errorf("histogram: %s", so)
	}
}

// With the new fields stripped, escalateAny off gives the same record as the
// plain escalate run: the generator is not asked for anything else.
func TestM7GeneratorInputUnchangedByEscalateAnyOff(t *testing.T) {
	var a, b []Input
	old := generate
	defer func() { generate = old }()
	generate = func(in Input) (*Result, error) { a = append(a, in); return old(in) }
	dirBT(t, m7Esc, genCollapsed(t, true), "")
	generate = func(in Input) (*Result, error) { b = append(b, in); return old(in) }
	dirBT(t, func(e *btEntry) { m7Esc(e); e.EscalateAny = false }, genCollapsed(t, true), "")
	if len(a) != 1 || len(b) != 1 {
		t.Fatalf("%d %d", len(a), len(b))
	}
	a[0].Source, b[0].Source = nil, nil
	if ja, jb := mustJSON(t, a[0]), mustJSON(t, b[0]); ja != jb {
		t.Fatalf("%s != %s", ja, jb)
	}
}

func mustJSON(t *testing.T, v any) string {
	t.Helper()
	b, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}
