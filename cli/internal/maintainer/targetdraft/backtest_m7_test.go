// m7Stub makes the plain run (no inference) stop with the given stops and
// serves the second run from next (the real generator when next is nil).
func m7Stub(plain []Stop, next func(Input) (*Result, error)) (calls *[]Input, restore func()) {
	old := generate
	var seen []Input
	generate = func(in Input) (*Result, error) {
		seen = append(seen, in)
		if !in.InferInstallPaths {
			return nil, &StopError{Stops: plain}
		}
		if next != nil {
			return next(in)
		}
		return old(in)
	}
	return &seen, func() { generate = old }
}

func m7Esc(e *btEntry) { e.CollapseDirectories, e.Escalate = true, true }
func m7EscAny(e *btEntry) {
	m7Esc(e)
	e.EscalateAny = true
}

func TestM7EscalateAnyOffIsTheOldBehaviour(t *testing.T) {
	for _, code := range []string{StopReservedGroup, StopNoCRDSource, StopGroupOwnedElsewhere} {
		calls, restore := m7Stub([]Stop{{Code: code, Subject: "g.example", Next: "x"}}, nil)
		rep, r := dirBT(t, m7Esc, genCollapsed(t, true), "")
		restore()
		if r.Class != ClassTypedStop || r.Escalated == nil || *r.Escalated || r.PlainStop != "" || len(r.PlainStops) != 0 || len(r.PlainStopSubjects) != 0 ||
			rep.Escalated != 0 || len(*calls) != 1 || len(r.Stops) != 1 || r.Stops[0] != code {
			t.Fatalf("%s: %+v %d", code, r, len(*calls))
		}
	}
	// The listed stops still escalate exactly as before, and record no plain list.
	calls, restore := m7Stub([]Stop{{Code: StopDuplicateCRD, Next: "x"}}, nil)
	_, r := dirBT(t, m7Esc, genCollapsed(t, true), "")
	restore()
	if r.Class != ClassReproduced || !*r.Escalated || r.PlainStop != StopDuplicateCRD || len(r.PlainStops) != 0 || len(*calls) != 2 {
		t.Fatalf("%+v", r)
	}
}

func TestM7EscalateAnyEscalatesAReservedGroupCoStop(t *testing.T) {
	plain := []Stop{{Code: StopReservedGroup, Subject: "apps", Next: "x"}, {Code: StopNoCRDSource, Subject: "config/a.yaml", Next: "x"}}
	second := func(Input) (*Result, error) {
		return nil, &StopError{Stops: []Stop{{Code: StopInstallPathAmbiguous, Subject: "config/crd", Next: "x"}}}
	}
	calls, restore := m7Stub(plain, second)
	rep, r := dirBT(t, m7EscAny, genCollapsed(t, true), "")
	restore()
	if len(*calls) != 2 || !(*calls)[1].InferInstallPaths {
		t.Fatalf("not escalated: %d", len(*calls))
	}
	if r.Class != ClassTypedStop || !*r.Escalated || rep.Escalated != 1 || r.PlainStop != StopNoCRDSource || r.Stops[0] != StopInstallPathAmbiguous {
		t.Fatalf("%+v", r)
	}
	if strings.Join(r.PlainStops, ",") != StopNoCRDSource+","+StopReservedGroup ||
		strings.Join(r.PlainStopSubjects, ";") != "no-crd-source:config/a.yaml;reserved-group:apps" ||
		strings.Join(r.StopSubjects, ";") != "install-path-ambiguous:config/crd" {
		t.Fatalf("%+v", r)
	}
	if rep.Histogram["second-level-stop:"+StopInstallPathAmbiguous] != 1 || rep.Histogram["escalated-from:"+StopNoCRDSource] != 1 || rep.Histogram["stop:"+StopInstallPathAmbiguous] != 0 {
		t.Fatalf("%v", rep.Histogram)
	}
}

func TestM7EscalatedOutcomeIsJudgedStrictly(t *testing.T) {
	plain := []Stop{{Code: StopReservedGroup, Subject: "apps", Next: "x"}}
	// Same generated bytes as the reviewed file: reproduced.
	_, restore := m7Stub(plain, nil)
	_, r := dirBT(t, m7EscAny, genCollapsed(t, true), "")
	restore()
	if r.Class != ClassReproduced || !*r.Escalated {
		t.Fatalf("%+v", r)
	}
	// A reviewed file that differs after escalation is differs, never a pass.
	_, restore = m7Stub(plain, nil)
	_, r = dirBT(t, m7EscAny, bytes.Replace(genCollapsed(t, true), []byte(`"minFrom": "`), []byte(`"minFrom": "0`), 1), "")
	restore()
	if r.Class != ClassDiffers || !*r.Escalated || r.GeneratedMinFrom == "" {
		t.Fatalf("%+v", r)
	}
}

func TestM7EscalateAnyNegatives(t *testing.T) {
	// escalateAny without escalate is refused.
	_, r := dirBT(t, func(e *btEntry) { e.EscalateAny = true }, genCollapsed(t, true), "")
	if r.Class != ClassHarnessError || !strings.Contains(r.Error, "requires escalate") {
		t.Fatalf("%+v", r)
	}
	// escalateAny keeps the other refusals (oracle).
	_, r = dirBT(t, func(e *btEntry) { m7EscAny(e); e.OraclePaths = true }, genCollapsed(t, true), "")
	if r.Class != ClassHarnessError {
		t.Fatalf("%+v", r)
	}
	// The harness's own stop and an empty stop list never escalate.
	if m7Escalates(btEntry{EscalateAny: true}, []string{StopMirrorMissing}) || m7Escalates(btEntry{EscalateAny: true}, nil) ||
		m7Escalates(btEntry{EscalateAny: true}, []string{StopReservedGroup, StopMirrorMissing}) {
		t.Fatal("must not escalate")
	}
	if !m7Escalates(btEntry{EscalateAny: true}, []string{StopReservedGroup}) || m7Escalates(btEntry{}, []string{StopReservedGroup}) ||
		m7Escalates(btEntry{}, []string{StopDuplicateCRD, StopReservedGroup}) || !m7Escalates(btEntry{}, []string{StopDuplicateCRD}) {
		t.Fatal("escalation table")
	}
}

func TestM7HalfBVsAttestless(t *testing.T) {
	res, err := Generate(collapseInputFor(collapseSource(nil), true))
	if err != nil {
		t.Fatal(err)
	}
	halfB := func(e *btEntry) { e.CollapseDirectories, e.Half = true, "B" }
	// Half B against a shipped file that is exactly half A: informational cause.
	rep, r := dirBT(t, halfB, res.A, "")
	if r.Class != ClassDiffers || r.Cause != CauseHalfBVsAttestless || r.Half != "B" || rep.Reproduced != 0 || rep.Histogram["cause:"+CauseHalfBVsAttestless] != 1 {
		t.Fatalf("%+v", r)
	}
	// Half A against the same file: reproduced, no cause.
	if _, r := dirBT(t, func(e *btEntry) { e.CollapseDirectories = true }, res.A, ""); r.Class != ClassReproduced || r.Cause != "" || r.Half != "A" {
		t.Fatalf("%+v", r)
	}
	// Half B against the real half B: reproduced.
	if _, r := dirBT(t, halfB, res.B, ""); r.Class != ClassReproduced {
		t.Fatalf("%+v", r)
	}
	// Half B against a file that is half A with another minFrom: not the artefact.
	other := bytes.Replace(res.A, []byte(`"minFrom": "`), []byte(`"minFrom": "0`), 1)
	if _, r := dirBT(t, halfB, other, ""); r.Class != ClassDiffers || r.Cause == CauseHalfBVsAttestless {
		t.Fatalf("%+v", r)
	}
	// Half A never takes the cause (the half is not the default-changed).
	if _, r := dirBT(t, func(e *btEntry) { e.CollapseDirectories = true }, res.B, ""); r.Class != ClassDiffers || r.Cause == CauseHalfBVsAttestless {
		t.Fatalf("%+v", r)
	}
}

func TestM7OracleNeverIncrementsStrict(t *testing.T) {
	f := newBT(t)
	f.m["entries"].([]any)[0].(map[string]any)["oraclePaths"] = true
	code, so, se := f.run(t, btOpen)
	if code != 0 {
		t.Fatalf("exit %d: %s %s", code, so, se)
	}
	for _, want := range []string{"alpha reproduced-oracle ", "strict (no oracle)=1/2\n", "oracle-assisted=1/2\n", "strict=1/2 "} {
		if !strings.Contains(so, want) {
			t.Errorf("missing %q in %s", want, so)
		}
	}
	// Both entries oracle: strict stays 0.
	f = newBT(t)
	for _, e := range f.m["entries"].([]any) {
		e.(map[string]any)["oraclePaths"] = true
	}
	_, so, _ = f.run(t, btOpen)
	if !strings.Contains(so, "strict (no oracle)=0/2\n") || !strings.Contains(so, "oracle-assisted=2/2\n") || !strings.Contains(so, "strict=0/2 ") {
		t.Fatalf("%s", so)
	}
	// Direct: an oracle result adds to OracleRepro only.
	rep, r := dirBT(t, func(e *btEntry) { e.CollapseDirectories, e.OraclePaths = true, true }, genCollapsed(t, true), "")
	if r.Class != ClassReproducedOracle || rep.Reproduced != 0 || rep.OracleRepro != 1 {
		t.Fatalf("%+v", rep)
	}
}

