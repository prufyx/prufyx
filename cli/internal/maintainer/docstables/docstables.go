// Package docstables renders the documentation tables that are generated
// from reviewed data compiled into Prufyx: the custom-resource table
// (internal/customresources/table.json) and the crd.version-removal targets
// (internal/extract/crdversions/targets.json). The tables say only what the
// data says; prose about them stays in the hand-written documents that link
// to them.
package docstables

import (
	"fmt"
	"strings"

	"github.com/prufyx/prufyx/cli/internal/customresources"
	"github.com/prufyx/prufyx/cli/internal/extract/crdversions"
)

// The generated files, relative to the CLI root.
const (
	CustomResourcesPath = "docs/generated/custom-resource-projects.md"
	CRDTargetsPath      = "docs/generated/crd-version-targets.md"
)

// File is one generated document.
type File struct {
	Path    string
	Content string
}

// Generate renders every generated document, in a fixed order.
func Generate() []File {
	return []File{
		{Path: CRDTargetsPath, Content: CRDTargets(crdversions.Targets)},
		{Path: CustomResourcesPath, Content: CustomResources(customresources.Projects(), customresources.ReservedGroups())},
	}
}

const header = "<!-- Generated by `prufyx-maintainer docs-tables` from %s; do not edit. -->\n\n"

// CustomResources renders the reviewed custom-resource table: every project
// with its catalog, fact and API groups, the provenance of the community
// projects, and the reviewed ownership records of reserved groups.
func CustomResources(projects []customresources.Project, reserved []customresources.ReservedGroup) string {
	var b strings.Builder
	fmt.Fprintf(&b, header, "internal/customresources/table.json")
	b.WriteString("# Custom-resource projects\n\n")
	b.WriteString("The reviewed table of projects whose custom-resource versions Prufyx records\n(see [../custom-resources.md](../custom-resources.md)).\n\n")
	b.WriteString("| Project | Catalog | Fact | API groups |\n| --- | --- | --- | --- |\n")
	for _, p := range projects {
		catalog := "CNCF"
		if p.Community() {
			catalog = "community"
		}
		groups := make([]string, 0, len(p.Groups))
		for _, g := range p.Groups {
			groups = append(groups, code(g.Name))
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", code(p.Slug), catalog, code(p.FactID()), strings.Join(groups, ", "))
	}
	b.WriteString("\n## Community catalog\n\n")
	b.WriteString("| Project | Name | Upstream repository | Licence |\n| --- | --- | --- | --- |\n")
	for _, p := range projects {
		if !p.Community() {
			continue
		}
		u := p.Upstream
		fmt.Fprintf(&b, "| %s | %s | %s | [%s](%s) |\n", code(p.Slug), cell(u.Name), u.Repository, code(u.License), u.LicenseSource)
	}
	b.WriteString("\n## Groups in reserved namespaces\n\n")
	b.WriteString("| Group | Project | Repository | Reason |\n| --- | --- | --- | --- |\n")
	for _, r := range reserved {
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", code(r.Name), code(r.Owner), r.Repository, cell(r.Reason))
	}
	return b.String()
}

// CRDTargets renders the crd.version-removal targets: one row per target
// with its catalog, repository, release tags, first line, whether it attests
// lines, the paths it reads and the number of reviewed exclusions.
func CRDTargets(targets []crdversions.Target) string {
	var b strings.Builder
	fmt.Fprintf(&b, header, "internal/extract/crdversions/targets.json")
	b.WriteString("# crd.version-removal targets\n\n")
	b.WriteString("The reviewed targets of the `crd.version-removal` extractor\n(see [../extractors/crd.version-removal.md](../extractors/crd.version-removal.md)).\n\n")
	b.WriteString("| Extractor id | Catalog | Repository | Release tags | First pair from | Attests lines | CRD manifests | Reviewed exclusions |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n")
	for _, t := range targets {
		catalog := "CNCF"
		if t.Catalog == crdversions.CatalogCommunity {
			catalog = "community"
		}
		tags := make([]string, 0, len(t.TagPrefixes))
		for _, p := range t.TagPrefixes {
			tags = append(tags, code(p+"X.Y.Z"))
		}
		attests := "no"
		if t.Attest {
			attests = "yes"
		}
		manifests := paths(t.Paths)
		if t.DeclaredChannel != "" {
			manifests = "channel " + code(t.DeclaredChannel) + " (declared): " + manifests
			for _, c := range t.Channels {
				manifests += "; channel " + code(c.Name) + ": " + paths(c.Paths)
			}
		}
		if r := t.Remote; r != nil {
			manifests += fmt.Sprintf("; from %d.%d: the files listed by %s of %s, at the tag %s names (%d pinned tags)", r.FromLine[0], r.FromLine[1], code(r.Directory+"/kustomization.yaml"), code(r.Repo), code(r.Kustomization), len(r.Pins))
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %d.%d | %s | %s | %d |\n", code(t.ExtractorID()), catalog, code(t.Repo), strings.Join(tags, ", then "), t.MinFrom[0], t.MinFrom[1], attests, manifests, len(t.Exclude))
	}
	return b.String()
}

func paths(specs []crdversions.PathSpec) string {
	out := make([]string, 0, len(specs))
	for _, p := range specs {
		s := code(p.Path)
		if p.Dir {
			where := "in"
			if p.Recursive {
				where = "anywhere under"
			}
			s = "files matching " + code(p.Match.String()) + " " + where + " " + code(p.Path)
		}
		if p.Optional {
			s += " (when present)"
		}
		out = append(out, s)
	}
	return strings.Join(out, ", ")
}

// code renders a value as inline code inside a table cell.
func code(s string) string { return "`" + cell(s) + "`" }

// cell escapes the characters that would end a table cell or row.
func cell(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}
