package communityapp

import (
	"sort"
	"strings"
)

// projectDocsHeader marks a generated page. The generator is
// TestProjectDocsFresh; it writes the pages when PRUFYX_UPDATE_DOCS=1.
const projectDocsHeader = "<!-- Generated by TestProjectDocsFresh (PRUFYX_UPDATE_DOCS=1 go test ./internal/communityapp -run TestProjectDocsFresh). Do not edit. -->\n"

// projectRoutes is the order in which a page lists the routes of a project.
var projectRoutes = []string{"check cncf", "check project", "prepare cncf", "prepare project"}

// renderProjectDocs builds the pages of cli/docs/projects, keyed by file
// name. The output is a pure function of the former usage texts: it holds no
// date, version or knowledge-pack data, so it changes only when those texts
// change. Project identity and rule coverage stay with `prufyx catalog cncf`.
func renderProjectDocs() map[string][]byte {
	pages := map[string][]byte{}
	usage := legacyUsage()
	slugs := legacySlugs()
	for _, slug := range slugs {
		var b strings.Builder
		b.WriteString("# " + slug + "\n\n" + projectDocsHeader + "\n")
		b.WriteString("Usage of `prufyx check` and `prufyx prepare` for this project, as\n")
		b.WriteString("`--project " + slug + " --help` on each route prints it. Identity, stage and rule\n")
		b.WriteString("coverage: `prufyx catalog cncf --project " + slug + "`. Shared flags, exit status and\n")
		b.WriteString("the reference text of each route: [routes.md](routes.md).\n")
		for _, route := range projectRoutes {
			var lines []legacyLine
			for _, l := range usage {
				if l.route != route {
					continue
				}
				for _, s := range l.slugs {
					if s == slug {
						lines = append(lines, l)
						break
					}
				}
			}
			if len(lines) == 0 {
				continue
			}
			b.WriteString("\n## " + route + "\n\n```text\n")
			for _, l := range lines {
				b.WriteString(l.text + "\n")
				for _, n := range l.notes {
					b.WriteString("  " + n + "\n")
				}
			}
			b.WriteString("```\n")
		}
		pages[slug+".md"] = []byte(b.String())
	}

	var idx strings.Builder
	idx.WriteString("# Per-project usage\n\n" + projectDocsHeader + "\n")
	idx.WriteString("One page per project that has its own `prufyx check` or `prufyx prepare` usage.\n")
	idx.WriteString("Shared flags, exit status and the other routes: [routes.md](routes.md).\n\n")
	for _, slug := range slugs {
		idx.WriteString("- [" + slug + "](" + slug + ".md)\n")
	}
	pages["README.md"] = []byte(idx.String())

	var rt strings.Builder
	rt.WriteString("# Routes\n\n" + projectDocsHeader + "\n")
	rt.WriteString("Usage that names no particular project, then the reference text of each\n")
	rt.WriteString("former long help, line for line.\n")
	byRoute := map[string][]string{}
	for _, l := range usage {
		if len(l.slugs) == 0 {
			byRoute[l.route] = append(byRoute[l.route], l.text)
		}
	}
	routes := make([]string, 0, len(byRoute))
	for r := range byRoute {
		routes = append(routes, r)
	}
	sort.Strings(routes)
	rt.WriteString("\n## Usage without a project\n")
	for _, route := range routes {
		rt.WriteString("\n### " + route + "\n\n```text\n")
		for _, t := range byRoute[route] {
			rt.WriteString(t + "\n")
		}
		rt.WriteString("```\n")
	}
	rt.WriteString("\n## Reference text\n")
	for _, s := range legacySources {
		var prose []string
		for _, l := range parseLegacy(s.text) {
			if !l.usage {
				prose = append(prose, l.text)
			}
		}
		if len(prose) == 0 {
			continue
		}
		rt.WriteString("\n### prufyx " + s.route + "\n\n```text\n" + strings.Join(prose, "\n") + "\n```\n")
	}
	pages["routes.md"] = []byte(rt.String())
	return pages
}
