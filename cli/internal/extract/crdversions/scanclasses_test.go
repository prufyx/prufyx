// classPair runs a pair whose listed paths hold from and to, with the
// files of fromFiles and toFiles next to them.
func classPair(t *testing.T, from, to string, fromFiles, toFiles map[string]string, exclude ...Exclusion) (extract.PairRecord, PairProof) {
	t.Helper()
	f := map[string]string{"deploy/crds/a.yaml": from}
	l := map[string]string{"deploy/crds/a.yaml": to}
	for p, c := range fromFiles {
		f[p] = c
	}
	for p, c := range toFiles {
		l[p] = c
	}
	s := newSynth(release{"v1.0.0", f}, release{"v1.1.0", l})
	return pairOf(t, runSynth(t, synthTarget(exclude...), s), "1.0.0", "1.1.0")
}

// quietPair runs a pair whose listed paths do not change (no rule), with
// file at path at both releases, and returns the later release's finding
// for it (nil when there is none).
func quietPair(t *testing.T, path, file string, exclude ...Exclusion) (extract.PairRecord, PairProof, *Finding) {
	t.Helper()
	alpha := crd("Alpha", "v1beta1", "v1")
	p, proof := classPair(t, alpha, alpha, map[string]string{path: file}, map[string]string{path: file}, exclude...)
	if proof.To == nil || proof.To.Scan == nil {
		t.Fatalf("no scan: %+v", p)
	}
	return p, proof, findingOf(proof.To.Scan, path)
}

func findingOf(s *ScanRecord, path string) *Finding {
	for i := range s.Findings {
		if s.Findings[i].Path == path {
			return &s.Findings[i]
		}
	}
	return nil
}

// Helm chart forms of the listed definitions, as upstream charts write
// them. kueue: a header comment, labels added by a directive-only include,
// an annotation under a condition, quoted expressions in spec.conversion.
// Its inline includes are not bounded, so it is not read.
func kueueTemplate(body string) string {
	head := "{{/* Code generated by yaml-processor. DO NOT EDIT. */}}\n\n---\n"
	return head + strings.Replace(body, "metadata:\n  name: ", "metadata:\n  annotations:\n    {{- if .Values.enableCertManager }}\n    cert-manager.io/inject-ca-from: {{ .Release.Namespace }}/{{ include \"kueue.fullname\" . }}-serving-cert\n    {{- end }}\n    controller-gen.kubebuilder.io/version: v0.17.1\n  labels:\n  {{- include \"kueue.labels\" . | nindent 4 }}\n  name: ", 1) + conversion("'{{ include \"kueue.fullname\" . }}-webhook-service'", "'{{ .Release.Namespace }}'")
}

// metallb: a plain definition whose conversion service names the release
// namespace.
func metallbTemplate(body string) string {
	return strings.Replace(body, "metadata:\n", "metadata:\n  annotations:\n    controller-gen.kubebuilder.io/version: v0.16.3\n", 1) + conversion("metallb-webhook-service", "{{ .Release.Namespace }}")
}

// cert-manager: a condition around the whole file, a conditional
// annotation and labels with expressions (the chart name here, where the
// chart writes an inline include, which is not read).
func certManagerTemplate(body string) string {
	meta := "metadata:\n  name: alphas.synth.example.io\n  {{- if .Values.crds.keep }}\n  annotations:\n    helm.sh/resource-policy: keep\n  {{- end }}\n  labels:\n    app: {{ .Chart.Name }}\n    app.kubernetes.io/instance: {{ .Release.Name }}\n    app.kubernetes.io/component: \"crds\"\n    # Generated labels {{- include \"labels\" . | nindent 4 }}\n"
	return "{{- if or .Values.crds.enabled .Values.installCRDs }}\n" + strings.Replace(body, "metadata:\n  name: alphas.synth.example.io\n", meta, 1) + "{{- end }}\n"
}

// longhorn: labels whose value is an include, with a literal label under
// it.
func longhornTemplate(body string) string {
	return strings.Replace(body, "metadata:\n", "metadata:\n  labels: {{- include \"longhorn.labels\" . | nindent 4 }}\n    longhorn-manager: \"\"\n", 1)
}

func conversion(name, namespace string) string {
	return "  conversion:\n    strategy: Webhook\n    webhook:\n      clientConfig:\n        caBundle: Cg==\n        service:\n          name: " + name + "\n          namespace: " + namespace + "\n          path: /convert\n      conversionReviewVersions:\n      - v1\n"
}

// A templated file whose served versions its literal lines determine is
// read in the open tree: an exact copy is templated-copy and does not
// block; one that is not a copy is unread, never a conflict or extra.
func TestTemplatedCopies(t *testing.T) {
	const path = "charts/kueue/templates/crd/alphas.yaml"
	from, to := crd("Alpha", "v1beta1", "v1"), crd("Alpha", "v1beta1:off", "v1")
	for name, form := range map[string]func(string) string{
		"metallb": metallbTemplate, "cert-manager": certManagerTemplate, "longhorn": longhornTemplate, "rook": rookTemplate,
	} {
		p, proof := classPair(t, from, to, map[string]string{path: form(from)}, map[string]string{path: form(to)})
		if p.Status != extract.PairDerived || len(p.Rules) != 1 || !proof.Completeness.Attestable {
			t.Fatalf("%s: %s %q %+v %+v", name, p.Status, p.Reason, proof.Completeness, proof.To.Scan.Findings)
		}
		f := findingOf(proof.To.Scan, path)
		if f == nil || f.Class != ClassTemplatedCopy || !slices.Equal(f.CRDs, []string{"alphas." + synthGroup}) || !slices.Equal(f.Served, []string{synthGroup + "/v1/Alpha"}) || !strings.Contains(f.Detail, "template directives removed") {
			t.Fatalf("%s: %+v", name, f)
		}
		if f.blocks() || f.opaque() || f.unreadable() || slices.Contains(proof.To.Scan.Copies, path) {
			t.Fatalf("%s: effects of %+v", name, f)
		}
		// Under a default-excluded directory too.
		_, _, f = quietPair(t, "test/"+path, form(from))
		if f == nil || f.Class != ClassTemplatedCopy || f.Location != "default: test" {
			t.Fatalf("%s in test/: %+v", name, f)
		}
	}
	// kueue's inline includes may render any text: unread.
	if _, _, f := quietPair(t, path, kueueTemplate(from)); f == nil || f.Class != ClassUnread || !strings.Contains(f.Detail, "whose output may span lines") {
		t.Fatalf("kueue: %+v", f)
	}
	// Still serving v1beta1 at the later anchor: unread in the open tree
	// (the rule is withheld), with the comparison in the detail.
	p, proof := classPair(t, from, to, map[string]string{path: metallbTemplate(from)}, map[string]string{path: metallbTemplate(from)})
	if p.Status != extract.PairWithheld || !strings.Contains(p.Reason, path+" is unread") || !strings.Contains(p.Reason, "not a copy of the listed paths: alphas.synth.example.io: versions") {
		t.Fatalf("differs: %s %q", p.Status, p.Reason)
	}
	if f := findingOf(proof.To.Scan, path); f == nil || f.Class != ClassUnread || !slices.Equal(f.CRDs, []string{"alphas." + synthGroup}) {
		t.Fatalf("differs: %+v", f)
	}
	// An unknown definition: unread, not extra.
	_, _, f := quietPair(t, path, metallbTemplate(crd("Beta", "v1")))
	if f == nil || f.Class != ClassUnread || !strings.Contains(f.Detail, "the listed paths do not hold") {
		t.Fatalf("unknown: %+v", f)
	}
	// Under a reviewed copies exclusion the reviewer's claim keeps its
	// classes: a copy is in Copies, one that differs is a conflict.
	copies := Exclusion{Path: "charts/kueue/templates/", Reason: "Helm chart templates of the listed definitions", Copies: true}
	p, proof = classPair(t, from, to, map[string]string{path: metallbTemplate(from)}, map[string]string{path: metallbTemplate(to)}, copies)
	if p.Status != extract.PairDerived || !proof.Completeness.Attestable || !slices.Equal(proof.To.Scan.Copies, []string{path}) || findingOf(proof.To.Scan, path) != nil {
		t.Fatalf("declared copy: %s %+v %+v", p.Status, proof.Completeness, proof.To.Scan)
	}
	p, proof = classPair(t, from, to, map[string]string{path: metallbTemplate(from)}, map[string]string{path: metallbTemplate(from)}, copies)
	if f := findingOf(proof.To.Scan, path); p.Status != extract.PairWithheld || f == nil || f.Class != ClassConflict || f.Location != "charts/kueue/templates/" {
		t.Fatalf("declared conflict: %s %q %+v", p.Status, p.Reason, f)
	}
	// Under a reviewed exclusion that does not declare copies a copy stays
	// templated-copy; one that cannot be read is excluded-unread.
	other := Exclusion{Path: "charts/kueue/templates/", Reason: "Helm chart templates of the listed definitions"}
	if _, _, f := quietPair(t, path, metallbTemplate(from), other); f == nil || f.Class != ClassTemplatedCopy || f.Location != other.Path {
		t.Fatalf("reviewed: %+v", f)
	}
	if _, _, f := quietPair(t, path, "{{- if .Values.a }}\n"+from, other); f == nil || f.Class != ClassExcludedUnread {
		t.Fatalf("reviewed unread: %+v", f)
	}
}

// rook: a condition around the whole file that trims the line break after
// it, on the first line, before a document that starts at column 0.
func rookTemplate(body string) string {
	return "{{- if .Values.crds.enabled -}}\n\n---\n" + body + "{{- end }}\n"
}

// A first-line condition that trims only line breaks joins nothing: the
// file is read, as a declared copy and in the open tree.
func TestTemplatedFirstLineTrim(t *testing.T) {
	const path = "deploy/charts/rook-ceph/templates/resources.yaml"
	from, to := crd("Alpha", "v1beta1", "v1"), crd("Alpha", "v1beta1:off", "v1")
	copies := Exclusion{Path: "deploy/charts/rook-ceph/templates/", Reason: "Helm chart templates of the listed definitions", Copies: true}
	p, proof := classPair(t, from, to, map[string]string{path: rookTemplate(from)}, map[string]string{path: rookTemplate(to)}, copies)
	if p.Status != extract.PairDerived || !proof.Completeness.Attestable || !slices.Equal(proof.To.Scan.Copies, []string{path}) || findingOf(proof.To.Scan, path) != nil {
		t.Fatalf("declared copy: %s %q %+v %+v", p.Status, p.Reason, proof.Completeness, proof.To.Scan)
	}
	p, proof = classPair(t, from, to, map[string]string{path: rookTemplate(from)}, map[string]string{path: rookTemplate(to)})
	if f := findingOf(proof.To.Scan, path); p.Status != extract.PairDerived || !proof.Completeness.Attestable || f == nil || f.Class != ClassTemplatedCopy {
		t.Fatalf("open tree: %s %q %+v", p.Status, p.Reason, f)
	}
}

// Every shape the reader does not prove is unread, wherever it lies.
func TestTemplatedShapesNotRead(t *testing.T) {
	const path = "charts/x/templates/crds.yaml"
	alpha := crd("Alpha", "v1beta1", "v1")
	beta := "  - name: v1beta1\n    served: true\n    storage: false\n    schema:\n      openAPIV3Schema:\n        type: object\n"
	wrap := func(body string) string { return "{{- if .Values.crds }}\n" + body + "{{- end }}\n" }
	cases := map[string]struct{ file, detail string }{
		"wrapper with else":                           {"{{- if .Values.a }}\n" + alpha + "{{- else }}\n" + crd("Alpha", "v1") + "{{- end }}\n", `"else"`},
		"wrapper without end":                         {"{{- if .Values.crds }}\n" + alpha, "a condition does not end"},
		"wrapper end before the last line":            {wrap(alpha) + "---\n" + crd("Beta", "v1"), "ends before its last line"},
		"condition around a version":                  {strings.Replace(alpha, beta, "  {{- if .Values.beta }}\n"+beta+"  {{- end }}\n", 1), `an "if" directive outside metadata`},
		"range under versions":                        {strings.Replace(alpha, beta, "  {{- range .Values.versions }}\n"+beta+"  {{- end }}\n", 1), `"range"`},
		"templated kind":                              {"# a CustomResourceDefinition of the chart\n" + strings.Replace(alpha, "kind: CustomResourceDefinition", "kind: {{ .Values.kind }}", 1), "outside metadata"},
		"templated apiVersion":                        {strings.Replace(alpha, "apiVersion: apiextensions.k8s.io/v1", "apiVersion: {{ .Values.api }}", 1), "outside metadata"},
		"templated served":                            {strings.Replace(alpha, "served: true", "served: {{ .Values.x }}", 1), "outside metadata"},
		"templated names.kind":                        {strings.Replace(alpha, "    kind: Alpha", "    kind: {{ .Values.kind }}", 1), "outside metadata"},
		"templated name":                              {strings.Replace(alpha, "  name: alphas.synth.example.io", "  name: {{ .Release.Name }}", 1), "metadata.name is a template expression"},
		"toYaml versions with literal entries":        {strings.Replace(alpha, "  versions:\n", "  versions: {{- toYaml .Values.v | nindent 2 }}\n", 1), "outside metadata"},
		"toYaml in conversion":                        {alpha + "  conversion:\n    webhook: {{ toYaml .Values.webhook | nindent 6 }}\n", "may span lines"},
		"if in metadata ends under spec":              {wrap(strings.Replace(strings.Replace(alpha, "metadata:\n", "metadata:\n  {{- if .Values.keep }}\n", 1), "  scope: Namespaced\n", "  {{- end }}\n  scope: Namespaced\n", 1)), "does not end inside it"},
		"wrapper end closes an if under spec":         {wrap(strings.Replace(alpha, "  scope: Namespaced\n", "  {{- if .Values.scoped }}\n  scope: Namespaced\n", 1)), "outside metadata"},
		"wrapper end closes an if in metadata":        {strings.Replace("{{- if .Values.crds }}\n"+alpha, "metadata:\n", "metadata:\n  {{- if .Values.keep }}\n", 1) + "{{- end }}\n", "does not end inside it"},
		"multi-expression directive line":             {strings.Replace(alpha, "metadata:\n", "metadata:\n  {{- if .Values.a }}{{- $b := 1 }}\n", 1), "trims a line break"},
		"multi-expression line in metadata":           {strings.Replace(alpha, "metadata:\n", "metadata:\n  {{ if .Values.a }}{{ $b := 1 }}\n", 1), `an "if" directive inside a line`},
		"variable in metadata":                        {strings.Replace(alpha, "metadata:\n", "metadata:\n  {{- $x := .Values.a }}\n", 1), "variable is assigned"},
		"define":                                      {"{{- define \"x\" }}\n" + alpha + "{{- end }}\n", `"define"`},
		"expression spans lines":                      {strings.Replace(alpha, "metadata:\n", "metadata:\n  labels: {{ include\n    \"x\" . }}\n", 1), "spans lines"},
		"trim after a first line, indented next":      {"{{- if .Values.crds -}}\n  ---\n" + alpha + "{{- end }}\n", "trims the line break after it"},
		"trim after a first line after a comment":     {"# rendered when crds are enabled\n{{- if .Values.crds -}}\n" + alpha + "{{- end }}\n", "trims the line break after it"},
		"trim after an end mid-file":                  {"{{- if .Values.crds }}\n" + alpha + "{{- end -}}\n---\n" + crd("Beta", "v1"), "trims the line break after it"},
		"brace pair inside a directive":               {strings.Replace(alpha, "metadata:\n", "metadata:\n  {{ if eq .x \"}}\" }}\n  {{ end }}\n", 1), "not well formed"},
		"text after a directive":                      {strings.Replace(alpha, "metadata:\n", "metadata:\n  {{ include \"x\" . }}--- #}}\n", 1), "not well formed"},
		"comment with a space":                        {strings.Replace(alpha, "metadata:\n", "metadata:\n  {{ /* c */ }}\n", 1), `a "/*" directive`},
		"values reference inline":                     {strings.Replace(alpha, "metadata:\n", "metadata:\n  labels:\n    app: {{ .Values.app }}\n", 1), "whose output may span lines"},
		"include inline":                              {strings.Replace(alpha, "metadata:\n", "metadata:\n  labels:\n    app: {{ include \"x\" . }}\n", 1), "whose output may span lines"},
		"tpl inline":                                  {strings.Replace(alpha, "metadata:\n", "metadata:\n  labels:\n    app: {{ tpl .Values.app . }}\n", 1), "whose output may span lines"},
		"files inline":                                {strings.Replace(alpha, "metadata:\n", "metadata:\n  labels:\n    app: {{ .Files.Get \"x\" }}\n", 1), "whose output may span lines"},
		"toYaml without indent":                       {strings.Replace(alpha, "metadata:\n", "metadata:\n  {{ toYaml .Values.meta }}\n", 1), "output does not end in indent or nindent"},
		"nindent 0":                                   {strings.Replace(alpha, "metadata:\n", "metadata:\n  labels:\n  {{- include \"x\" . | nindent 0 }}\n", 1), "output does not end in indent or nindent"},
		"release name inside a with":                  {strings.Replace(alpha, "metadata:\n", "metadata:\n  {{- with .Values.x }}\n  labels:\n    app: {{ .Release.Name }}\n  {{- end }}\n", 1), "whose output may span lines"},
		"trim after a directive":                      {strings.Replace(alpha, "metadata:\n", "metadata:\n  {{- if .Values.a -}}\n  {{- end }}\n", 1), "trims the line break after it"},
		"inline trim joins lines":                     {strings.Replace(alpha, "  name: alphas.synth.example.io\n", "  name: alphas.synth.example.io\n  {{- .Values.extra }}: x\n", 1), "trims a line break"},
		"comment expression under spec":               {strings.Replace(alpha, "  scope: Namespaced\n", "  # {{ toYaml .Values.extra | nindent 2 }}\n  scope: Namespaced\n", 1), "outside metadata"},
		"key with expression and children under spec": {strings.Replace(alpha, "  names:\n", "  names: {{ include \"x\" . }}\n", 1), "outside metadata"},
		"directive under status":                      {alpha + "status:\n  {{- include \"x\" . }}\n", `an "include" directive outside metadata`},
		"v1beta1 template":                            {strings.Replace(legacyCRD("Alpha", "v1beta1", "v1"), "metadata:\n", "metadata:\n  labels:\n    app: {{ .Release.Name }}\n", 1), "only apiextensions.k8s.io/v1 is read"},
	}
	for name, tc := range cases {
		info := summarize(kindData, []byte(tc.file))
		if info.template == nil || info.template.unread == "" || !strings.HasPrefix(info.template.unread, templateUnread) || !strings.Contains(info.template.unread, tc.detail) {
			t.Errorf("%s: %+v", name, info.template)
			continue
		}
		// A finding in the open tree, never absent, withholding the rule
		// of a pair at its later anchor.
		_, proof, f := quietPair(t, path, tc.file)
		if f == nil || f.Class != ClassUnread || f.Detail != info.template.unread || proof.Completeness.Attestable {
			t.Errorf("%s: %+v", name, f)
		}
		p, _ := classPair(t, alpha, crd("Alpha", "v1beta1:off", "v1"), nil, map[string]string{path: tc.file})
		if p.Status != extract.PairWithheld || !strings.Contains(p.Reason, path+" is unread") {
			t.Errorf("%s: %s %q", name, p.Status, p.Reason)
		}
	}
	// A templated kind with the kind name only in a comment was not a
	// finding before: it is unread now.
	if info := summarize(kindData, []byte(cases["templated kind"].file)); info.kindLike || !info.template.kindTemplated {
		t.Fatalf("templated kind: %+v", info)
	}
	// A metadata line that is not the metadata of a document (inside a
	// flow mapping opened above it) does not open a metadata block.
	flow := "apiVersion: apiextensions.k8s.io/v1\nkind: CustomResourceDefinition\nspec: {group: synth.example.io, names: {kind: Alpha, plural: alphas}, scope: Namespaced, versions: [{name: v1, served: true, storage: true}],\nmetadata:\n  {{- if .Values.a }}\n  x: y}\n  {{- end }}\nmetadata:\n  name: alphas.synth.example.io\n"
	if tr := readTemplate([]byte(flow)); tr.unread == "" {
		t.Fatalf("flow: %+v", tr)
	}
}

// Templated bytes are read by the template reader only: neither a patch
// fragment below a declared definition directory nor a v1beta1 copy is
// accepted with template syntax in it.
func TestTemplatedBytesOnlyReadAsTemplates(t *testing.T) {
	label := func(s string) string {
		return strings.Replace(s, "metadata:\n", "metadata:\n  labels:\n    app: {{ .Release.Name }}\n", 1)
	}
	alpha := crd("Alpha", "v1beta1", "v1")
	files := map[string]string{
		"deploy/kustomization.yaml":             synthKustomization,
		"deploy/patches/webhook_in_alphas.yaml": label(webhookFragment),
		"deploy/v1beta1/a.yaml":                 label(legacyCRD("Alpha", "v1beta1", "v1")),
	}
	_, proof := classPair(t, alpha, alpha, files, files)
	for _, p := range []string{"deploy/patches/webhook_in_alphas.yaml", "deploy/v1beta1/a.yaml"} {
		info := summarize(kindData, []byte(files[p]))
		if info.template == nil || info.legacy != nil || info.fragment != nil {
			t.Fatalf("%s: %+v", p, info)
		}
		if f := findingOf(proof.To.Scan, p); f == nil || f.Class != ClassUnread || !strings.HasPrefix(f.Detail, templateUnread) {
			t.Errorf("%s: %+v", p, f)
		}
	}
}

// Literal text after an action on the same line is rendered: a second
// definition hidden behind actions that end in a comment is not read,
// whether its lines are at column 0 or inside metadata.
func TestTemplatedSmuggledText(t *testing.T) {
	const path = "charts/x/templates/crds.yaml"
	alpha := crd("Alpha", "v1")
	var hidden, indented strings.Builder
	for _, line := range strings.Split(strings.TrimSuffix("---\n"+crd("Alpha", "v1beta1", "v1"), "\n"), "\n") {
		hidden.WriteString("{{ include \"x\" . }}" + line + " #}}\n")
		indented.WriteString("  {{ include \"x\" . }}" + line + " #}}\n")
	}
	for name, file := range map[string]string{
		"column 0":        strings.Replace(alpha, "  name: alphas.synth.example.io\n", "  name: alphas.synth.example.io\n"+hidden.String(), 1),
		"inside metadata": strings.Replace(alpha, "  name: alphas.synth.example.io\n", "  name: alphas.synth.example.io\n"+indented.String(), 1),
		"no closing pair": strings.Replace(alpha, "  name: alphas.synth.example.io\n", "  name: alphas.synth.example.io\n"+strings.ReplaceAll(indented.String(), " #}}", ""), 1),
	} {
		p, proof := classPair(t, alpha, alpha, map[string]string{path: file}, map[string]string{path: file})
		if f := findingOf(proof.To.Scan, path); f == nil || f.Class != ClassUnread || proof.Completeness.Attestable {
			t.Errorf("%s: %s %+v", name, p.Status, f)
		}
	}
	// A comment in the lexer's forms is removed; a release name and a
	// quoted value are read.
	for _, ins := range []string{"  {{/* c */}}\n", "  {{- /* c */}}\n", "  labels:\n    a: {{ .Release.Name }}\n    b: {{ .Values.b | quote }}\n"} {
		if tr := readTemplate([]byte(strings.Replace(alpha, "metadata:\n", "metadata:\n"+ins, 1))); tr.unread != "" || len(tr.crds) != 1 {
			t.Errorf("%q: %+v", ins, tr)
		}
	}
	// A spec that is itself a placeholder is not read.
	if why := templatedFields(nil, []any{map[string]any{"kind": crdKind, "spec": placeholder}}, nil, nil, &templateRead{}); why != "spec holds a template expression" {
		t.Errorf("spec: %q", why)
	}
}

// The blob summary depends on the bytes only: the same templated bytes at
// two paths read the same, and each path is classified by its location.
func TestTemplatedSummaryIsAFunctionOfTheBytes(t *testing.T) {
	alpha := crd("Alpha", "v1beta1", "v1")
	for _, file := range []string{metallbTemplate(alpha), "{{- if .Values.a }}\n" + alpha} {
		a, b := summarize(kindData, []byte(file)), summarize(kindData, []byte(file))
		if !reflect.DeepEqual(a, b) {
			t.Fatalf("%+v %+v", a, b)
		}
		p, proof := classPair(t, alpha, alpha, map[string]string{"a/crds.yaml": file, "b/c/crds.yaml": file}, map[string]string{"a/crds.yaml": file, "b/c/crds.yaml": file})
		fa, fb := findingOf(proof.To.Scan, "a/crds.yaml"), findingOf(proof.To.Scan, "b/c/crds.yaml")
		if fa == nil || fb == nil || fa.Class != fb.Class || fa.Detail != fb.Detail || fa.SHA256 != fb.SHA256 {
			t.Fatalf("%s: %+v %+v", p.Status, fa, fb)
		}
	}
}

// Go code that builds a definition is go-defined: it blocks attestation,
// withholds the rules at the later anchor and is named in the reasons.
func TestGoDefined(t *testing.T) {
	const path = "pkg/crd/build.go"
	src := "package crd\n\nfunc New() *apiextv1.CustomResourceDefinition {\n\treturn &apiextv1.CustomResourceDefinition{ObjectMeta: metav1.ObjectMeta{Name: \"alphas.synth.example.io\"}}\n}\n"
	p, proof, f := quietPair(t, path, src)
	if f == nil || f.Class != ClassGoDefined || f.Detail != "a CustomResourceDefinition built in Go code: its served versions are not read" {
		t.Fatalf("finding %+v", f)
	}
	if !f.blocks() || !f.opaque() || !f.unreadable() || p.Status != extract.PairDerived || proof.Completeness.Attestable || !strings.Contains(strings.Join(proof.Completeness.Reasons, "\n"), "found go-defined files") {
		t.Fatalf("pair %s %+v", p.Status, proof.Completeness)
	}
	p, _ = classPair(t, crd("Alpha", "v1beta1", "v1"), crd("Alpha", "v1beta1:off", "v1"), nil, map[string]string{path: src})
	if p.Status != extract.PairWithheld || !strings.Contains(p.Reason, path+" is go-defined") {
		t.Fatalf("withheld %s %q", p.Status, p.Reason)
	}
}

// The effects of the new classes, and their place under each location.
func TestNewClassEffects(t *testing.T) {
	if f := (Finding{Class: ClassTemplatedCopy}); f.blocks() || f.opaque() || f.unreadable() {
		t.Errorf("%s has effects", f.Class)
	}
	reviewed := place{kind: locReviewed, entry: "x/"}
	for c, want := range map[string]string{ClassTemplatedCopy: ClassTemplatedCopy, ClassGoDefined: ClassExcludedUnread} {
		if got := placed(Finding{Class: c}, reviewed); got.Class != want || got.Location != "x/" {
			t.Errorf("%s under a reviewed exclusion: %+v", c, got)
		}
	}
	if got := placed(Finding{Class: ClassGoDefined}, place{kind: locReviewed, entry: "x/", copies: true}); got.Class != ClassGoDefined {
		t.Errorf("go-defined among declared copies: %+v", got)
	}
	if (Finding{Class: ClassGoDefined, Location: "default: test"}).unreadable() {
		t.Error("go-defined under a default-excluded directory narrows the rules")
	}
}
